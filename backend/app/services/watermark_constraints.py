"""ขนาดภาพขั้นต่ำที่ฝังลายน้ำแล้วยังตรวจสอบย้อนกลับได้

ลายน้ำของระบบนี้คือ QR ของค่าแฮช SHA-256 (64 ตัวอักษร) ที่ถูกฝังลงซับแบนด์
ของ DWT ขนาดซับแบนด์ถูกกำหนดโดยขนาดภาพตามลำดับนี้

    ด้านสั้นของภาพ
      -> ROI สี่เหลี่ยมจัตุรัสกลางภาพ ปัดลงให้หาร 2**level ลงตัว
      -> ซับแบนด์ = ROI // 2**level      <- QR ทั้งอันต้องลงในนี้

ยิ่งภาพเล็ก ซับแบนด์ยิ่งเล็ก จนโมดูลของ QR ถูกบีบเละและถอดกลับไม่ได้เลย
ที่อันตรายคือกระบวนการ "ฝัง" ไม่ได้ล้มเหลว มันสร้างไฟล์ลายน้ำออกมาตามปกติ
ความเสียหายจะโผล่ตอนตรวจสอบเท่านั้น จึงต้องกันตั้งแต่ตอนอัปโหลด

MIN_BAND_PX มาจากการวัดจริงทั้งไปป์ไลน์ (ฝัง -> เซฟ JPEG q95 -> อ่านกลับ -> ถอด)
    ซับแบนด์ 75 px  ถอดไม่ออก
    ซับแบนด์ 78 px  ถอดออก
ตั้งเกณฑ์ไว้ที่ 80 เพื่อเผื่อขอบจากการบีบอัดที่หนักกว่าในการใช้งานจริง
"""

MIN_BAND_PX = 80

# ระดับ DWT ที่ระบบใช้จริง ต้องตรงกับค่าตั้งต้นของ DigitalWatermarkingSystem
# ไม่ import ตัวคลาสมาอ่านตอนรัน เพราะโมดูลนี้ถูกเรียกในเส้นทางที่เทสต์ mock
# ตัวฝังลายน้ำไว้ การอ่าน .level จาก Mock จะได้ค่าที่ใช้คำนวณไม่ได้
# กันค่าหลุดจากกันด้วยเทสต์ WatermarkConstraintsTests แทน
WATERMARK_LEVEL = 3


def min_source_side(level: int | None = None) -> int:
    """ความยาวด้านสั้นที่สุดของภาพที่ยังฝังลายน้ำแล้วตรวจสอบกลับได้

    ROI ถูกปัดลงเป็นพหุคูณของ 2**level ดังนั้นเงื่อนไข ซับแบนด์ >= MIN_BAND_PX
    ย่อลงเหลือ ด้านสั้น >= MIN_BAND_PX * 2**level พอดี
    """
    unit = 2 ** (WATERMARK_LEVEL if level is None else level)
    return MIN_BAND_PX * unit


def is_watermarkable(height: int, width: int, level: int | None = None) -> bool:
    """ภาพขนาดนี้ฝังลายน้ำแล้วตรวจสอบย้อนกลับได้หรือไม่"""
    return min(height, width) >= min_source_side(level)
